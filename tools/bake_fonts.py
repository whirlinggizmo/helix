"""Bake the built-in font (JetBrains Mono, printable ASCII) into a distance-field atlas, as a generated Haxe class.

generated/fonts/GeneratedFont.hx (committed and shipped in the library: tools/gen_code.py) holds the atlas, zlib-compressed and
base64-encoded, and each glyph's place and metrics; Font.builtIn() decodes it. Regenerated when the font, the baker or this script is
newer than the output, as the shaders are; its atlas and metrics are scratch in build/generated/fonts. The baker is HeliX's own (helix.font.TrueType and FontBaker, which bake loaded fonts at run time too), run
under the Haxe interpreter by tools/bake_fonts/FontBake.hx."""
import base64
import json
from pathlib import Path
import subprocess
import sys
import zlib

ROOT=Path(__file__).resolve().parents[1]
FONT=ROOT/'vendor/fonts/JetBrainsMono/JetBrainsMono-Regular.ttf'
BAKER=[ROOT/'tools/bake_fonts/FontBake.hx',ROOT/'src/helix/font/TrueType.hx',ROOT/'src/helix/font/FontBaker.hx']
OUT=ROOT/'generated/fonts'
SCRATCH=ROOT/'build/generated/fonts'
# Pixel height and distance-field padding: 32 and 6 keep edges clean from small text to about 4x up, in a 512x256 atlas.
HEIGHT,PADDING,WIDTH=32,6,512

def generate(force=False,out=OUT):
    """Write out/GeneratedFont.hx when it's missing or older than what makes it (or force)."""
    output=out/'GeneratedFont.hx'
    if not force and output.is_file() and output.stat().st_mtime>=max(p.stat().st_mtime for p in (FONT,*BAKER,Path(__file__))):return output
    out.mkdir(parents=True,exist_ok=True);SCRATCH.mkdir(parents=True,exist_ok=True)
    atlas,metrics=SCRATCH/'atlas.r8',SCRATCH/'metrics.json'
    # The baker leaves the atlas's last row free and its last texel fully inside: Batch2D draws untextured shapes with it.
    subprocess.run(['haxe','-cp','src','-cp','tools/bake_fonts','--run','FontBake',str(FONT),str(HEIGHT),str(PADDING),str(WIDTH),str(atlas),str(metrics)],cwd=ROOT,check=True)
    m=json.loads(metrics.read_text(encoding='utf-8'));raw=atlas.read_bytes()
    data=base64.b64encode(zlib.compress(bytes(raw),9)).decode()
    glyphs=','.join(f'{g[0]},{g[1]},{g[2]},{g[3]},{g[4]},{g[5]}' for g in m['glyphs'])
    advances=','.join(f'{g[6]:.4f}' for g in m['glyphs'])
    output.write_text(f'''// Generated by tools/bake_fonts.py from {FONT.relative_to(ROOT).as_posix()}: do not edit.
/** The built-in font's distance-field atlas and metrics (JetBrains Mono, SIL OFL 1.1: see THIRD_PARTY_NOTICES.md). */
class GeneratedFont {{
	/** Atlas size in texels, one byte each: 128 is the outline, falling {128/PADDING:g} a texel outward. */
	public static inline var width = {m["width"]};
	public static inline var height = {m["height"]};
	/** The height the glyphs were baked at, and the font's ascent and descent there, in pixels. */
	public static inline var pixelHeight = {m["pixelHeight"]};
	public static inline var ascent = {m["ascent"]:.4f};
	public static inline var descent = {m["descent"]:.4f};
	public static inline var lineGap = {m["lineGap"]:.4f};
	/** The first character; glyphs follow in order to tilde. */
	public static inline var first = {m["first"]};
	/** Per glyph: atlas x, y, width, height, then x and y offset from the pen on the baseline, in pixels. */
	public static final glyphs:Array<Int> = [{glyphs}];
	/** Per glyph: how far the pen moves, in pixels. */
	public static final advances:Array<Float> = [{advances}];
	/** The white texel, for untextured shapes. */
	public static inline var whiteX = {m["width"]-1};
	public static inline var whiteY = {m["height"]-1};
	/** The atlas, zlib-compressed, base64. */
	public static final atlas = "{data}";
}}
''', encoding='utf-8', newline='\n')
    return output

if __name__=='__main__':
    import cli
    p=cli.parser(__doc__);p.add_argument('--regenerate',action='store_true',help='bake it again even when it is current')
    print(generate(p.parse_args().regenerate))
