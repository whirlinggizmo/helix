#!/usr/bin/env python3
"""Writes the generated parts of helix-ray's Raylib.hx, Raymath.hx and Rlgl.hx, and the types helix-ray doesn't have yet.

Raylib.hx has RCore, RShapes, RTextures, RText, RModels, RAudio and RAsync, in raylib's module order; Raymath.hx has RMath and Rlgl.hx
RRlgl. The sections (ray/src/helix/ray/raylib/) are read as the compiler describes them (haxe -xml), never by matching their text
(docs/CONVENTIONS.md). Each file's generated part has two halves:

  - its header's constants that aren't written by hand: raylib's enum values and number defines (ray/vendor/raylib/raylib_api.json,
    raymath_api.json and rlgl_api.json, raylib's own description of its API, rlgl's and raymath's made by raylib's parser);
  - its functions: every function of its sections as an inline forward with its doc comment, under a heading naming its module and file;
    then each function a program can't call, as a macro with raylib's signature whose call reports its message where it is
    (helix.platform.macros.Build), so the build stops there and the call still has raylib's type. A section's function marked
    `@:unsupported("...")` is one helix-ray won't have (Build.unsupported), one marked `@:unimplemented("...")` one it doesn't have yet
    (Build.unimplemented), and one of the header's that no section writes is declared `@:unimplemented` with "Not implemented".

So each file reads like its header, and a call costs nothing more. The sections are compiled with the files' generated functions left
out, so a stale file doesn't stop its own making. A struct of raylib's that helix-ray has no type for is written as a type of its own,
with raylib's fields, in a file that says it is generated; a type written by hand in its place is left alone.

    python3 tools/gen_raylib.py [--check]

The rest of each file (its own constants and macro functions) is written by hand, outside the markers. --check writes nothing and exits 1
when anything generated is stale, as helix.py test runs it."""
import json
import re
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAY = ROOT / 'ray/src/helix/ray'
VENDOR = ROOT / 'ray/vendor/raylib'
BEGIN = '\t// ---- generated by tools/gen_raylib.py: begin ----'
END = '\t// ---- generated by tools/gen_raylib.py: end ----'
# Between the generated constants and the generated functions.
MIDDLE = '\t// ---- generated by tools/gen_raylib.py: functions ----'
# A type file's first line when the type is generated.
GENERATED_TYPE = "// Generated by tools/gen_raylib.py from raylib's API: helix-ray doesn't have it yet. When it does, write it here by hand."
# Each file, its sections (raylib's modules, in raylib.h's order, and helix-ray's own last) and the API whose missing functions it
# declares; raymath apart, as raylib has it.
TARGETS = {
    'Raylib.hx': ([
        ('RCore', 'rcore: the window and frame, input, files, cameras and shaders'),
        ('RShapes', 'rshapes: 2D shapes and collisions'),
        ('RTextures', 'rtextures: textures, render textures and colors'),
        ('RText', 'rtext: text'),
        ('RModels', 'rmodels: 3D shapes, models, meshes and rays'),
        ('RAudio', 'raudio: sound'),
        ('RAsync', "the async loads, helix-ray's own in place of raylib's that wait for a file"),
    ], 'raylib_api.json', 'raylib.h'),
    'Raymath.hx': ([('RMath', 'raymath: vectors, matrices and quaternions')], 'raymath_api.json', 'raymath.h'),
    'Rlgl.hx': ([('RRlgl', 'rlgl: the matrix stack, immediate drawing and render state')], 'rlgl_api.json', 'rlgl.h'),
}
SECTIONS = [s for sections, _, _ in TARGETS.values() for s in sections]
# A function of raylib's: capitalized, as raylib's names are, or rl (or rlgl) and a capital, as rlgl's.
FUNCTION = re.compile(r'(?:rlgl|rl)?[A-Z]\w*')
# The section metas that make a function a refusal, and the helper (helix.platform.macros.Build) each calls.
REFUSALS = {':unsupported': 'unsupported', ':unimplemented': 'unimplemented'}
# A refusal's message naming what to use instead: "See Name(its parameters)".
INSTEAD = re.compile(r'See (\w+)\((.*?)\)')
# C's number types as Haxe's.
NUMBERS = {'int': 'Int', 'unsigned int': 'Int', 'long': 'Int', 'char': 'Int', 'unsigned char': 'Int', 'unsigned short': 'Int',
           'float': 'Float', 'double': 'Float', 'bool': 'Bool', 'void': 'Void'}
# raymath's arrays of floats, the buffers raudio keeps behind a pointer, and rlgl's own GPU state.
OPAQUE = {'float3': 'Array<Float>', 'float16': 'Array<Float>', 'rAudioBuffer *': 'Dynamic', 'rAudioProcessor *': 'Dynamic'}
OPAQUE.update({f'{name}{pointer}': 'Dynamic' for name in ('rlVertexBuffer', 'rlDrawCall', 'rlRenderBatch', 'rlglData', 'rl_float16')
               for pointer in ('', ' *')})
# A parameter name Haxe reserves, and the name helix-ray gives it.
KEYWORDS = {'dynamic': 'isDynamic'}


def haxe_type(c, callbacks, many):
    """A C type of raylib's as Haxe writes it. A pointer to a struct is the struct, or an array of them when many (a parameter named
    for many, a field, a result); a pointer to numbers is an array; text is a String, bytes are Bytes, a callback a function type."""
    c = c.replace('const ', '').strip()
    if c in OPAQUE:
        return OPAQUE[c]
    if c in callbacks:
        return callbacks[c]
    array = re.fullmatch(r'(\w+)\[\d+\]', c)
    if array:
        return 'String' if array.group(1) == 'char' else f'Array<{haxe_type(array.group(1), callbacks, False)}>'
    if c == 'char *':
        return 'String'
    if c == 'char **':
        return 'Array<String>'
    if c == 'unsigned char *':
        return 'haxe.io.Bytes'
    if c == 'void *':
        return 'Dynamic'
    if c.endswith('**'):
        inner = haxe_type(c[:-2].strip(), callbacks, False)
        return f'Array<{inner}>' if many == 'parameter' else f'Array<Array<{inner}>>'
    if c.endswith('*'):
        pointed = c[:-1].strip()
        inner = haxe_type(pointed, callbacks, False)
        return f'Array<{inner}>' if many or pointed in NUMBERS else inner
    return NUMBERS.get(c, c)


def sentence(text):
    """raylib's description as a sentence."""
    text = text.strip().rstrip('.')
    return text[0].upper() + text[1:] + '.' if text else ''


def callback_types(api):
    """raylib's callbacks as Haxe's function types, null for none; raylib's va_list left out, as helix-ray's TraceLog has none."""
    out = {}
    for c in api.get('callbacks', []):
        args = ', '.join(f"{p['name']}:{haxe_type(p['type'], {}, True)}" for p in c.get('params', []) if p['type'] != 'va_list')
        out[c['name']] = f"Null<({args}) -> {haxe_type(c['returnType'], {}, True)}>"
    return out


def wrapped(line):
    """A signature as the formatter lays it out: past 160 columns (a tab is 4), broken after the last comma that fits, the rest three tabs
    in."""
    if len(line.expandtabs(4)) <= 160:
        return [line]
    # Broken only between parameters, never inside a parameter's type.
    commas, depth = [], 0
    for i, c in enumerate(line):
        depth += c in '(<[' 
        depth -= c in ')]' or c == '>' and line[i - 1] != '-'  # a function type's arrow closes nothing
        if c == ',' and depth == 1 and len(line[:i + 1].expandtabs(4)) < 160:
            commas.append(i)
    cut = commas[-1]
    return [line[:cut + 1], '\t\t\t' + line[cut + 2:]]


def qualified(haxe):
    """A Haxe type with helix-ray's types given their package, as an expression typed in the program's own scope needs them."""
    names = {p.stem for p in RAY.glob('*.hx')}
    return re.sub(r'\b([A-Z]\w*)\b', lambda m: f'helix.ray.{m.group(1)}' if m.group(1) in names else m.group(1), haxe)


def refusal(name, params, result, message, doc, kind='unimplemented', full=None):
    """A function helix-ray declares but doesn't have, as a macro: a call reports message where it is, through Build's kind (unimplemented
    or unsupported), and has raylib's result type; full is the result with its types' packages, else qualified from result."""
    rest = {n for n, t in params if re.match(r'(haxe\.extern\.)?Rest<', t)}
    signature = ', '.join(f'{n}:Array<Expr>' if n in rest else f'{n}:ExprOf<{t}>' for n, t in params)
    becomes = {'Void': '{}', 'Int': '(0 : Int)', 'Float': '(0.0 : Float)', 'Bool': '(false : Bool)'}.get(result, f'(null : {full or qualified(result)})')
    return [f'\t/** {doc} */', *wrapped(f'\tpublic static macro function {name}({signature}):ExprOf<{result}>'),
            *body(f'\t\treturn helix.platform.macros.Build.{kind}("{message}", macro{becomes if becomes.startswith("(") else " " + becomes});'), '']


def body(line):
    """A refusal's body as the formatter lays it out: past 160 columns, broken after the message, the result three tabs in."""
    if len(line.expandtabs(4)) <= 160:
        return [line]
    head, tail = line.rsplit(', macro', 1)
    return [head + ',', '\t\t\tmacro' + tail]


def stub(f, header, callbacks):
    """A function of raylib's helix-ray doesn't have, with raylib's signature: a call to it doesn't compile."""
    params, given = [], f.get('params', [])
    for i, p in enumerate(given):
        if p['type'] == '...':
            params.append(('args', 'haxe.extern.Rest<Dynamic>'))
            continue
        following = given[i + 1]['name'].lower() if i + 1 < len(given) else ''
        many = 'parameter' if p['name'].endswith('s') or 'count' in following or following == 'instances' else False
        params.append((KEYWORDS.get(p['name'], p['name']), haxe_type(p['type'], callbacks, many)))
    name = f['name']
    doc = f"raylib's `{name}` ({header}): not in helix-ray yet, so a call to it doesn't compile. {sentence(f.get('description', ''))}".strip()
    return refusal(name, params, haxe_type(f['returnType'], callbacks, True), f'{name}: Not implemented', doc)


def type_text(node, full=False):
    """A type as Haxe writes it, from haxe -xml's type element: helix-ray's own types by their short names (a file in helix.ray finds
    them), or full with their packages."""
    if node.tag in ('c', 'x', 't', 'e'):
        path = node.get('path')
        name = path if full or path.count('.') != 2 or not path.startswith('helix.ray.') else path.rsplit('.', 1)[1]
        params = [type_text(c, full) for c in node]
        return name + (f'<{", ".join(params)}>' if params else '')
    if node.tag == 'd':
        return 'Dynamic'
    if node.tag == 'f':
        kids = list(node)
        names = node.get('a', '').split(':') if node.get('a') else []
        args = [type_text(k, full) for k in kids[:-1]]
        result = type_text(kids[-1], full)
        if not args:
            return f'Void->{result}'
        if len(args) == 1 and not any(names) and kids[0].tag != 'f':
            return f'{args[0]}->{result}'
        named = [f'{n.lstrip("?")}:{t}' if n else t for n, t in zip(names + [''] * len(args), args)]
        return f'({", ".join(named)}) -> {result}'
    return node.tag


class Function:
    """A section's function as the compiler describes it: its name, its parameters (name, type, written as Haxe writes each), its result,
    its doc comment, and the refusal its meta asks for, if any (Build's helper and the message)."""

    def __init__(self, node):
        self.name = node.tag
        self.line = int(node.get('line', 0))
        f = node.find('f')
        kids = list(f)
        names = f.get('a').split(':') if f.get('a') else []
        values = f.get('v', '').split(':') if f.get('v') else [''] * len(names)
        self.params = []
        for name, kid, value in zip(names, kids[:-1], values + [''] * len(names)):
            text = type_text(kid)
            written = f'{name.lstrip("?")}:{text} = {value}' if value else f'{name}:{text}'
            self.params.append((name.lstrip('?'), text, written, type_text(kid, True)))
        self.result = type_text(kids[-1])
        self.full_result = type_text(kids[-1], True)
        doc = node.find('haxe_doc')
        self.doc = doc.text if doc is not None else ''
        self.refusal = None
        meta = node.find('meta')
        for m in meta if meta is not None else []:
            if m.get('n') in REFUSALS:
                # The meta's argument as written, a string literal: the message is inside its quotes.
                self.refusal = (REFUSALS[m.get('n')], m.find('e').text[1:-1])

    def signature(self):
        """Its parameters as a section writes them."""
        return ', '.join(p[2] for p in self.params)


def described(texts):
    """The sections' functions and each file's members written by hand, as the compiler describes them (haxe -xml). The sections are
    compiled over a copy of ray/src whose files keep only their generated constants (which the sections name), so a stale file doesn't
    stop its own making. Returns ({section: [Function, in order]}, {file: names written by hand})."""
    sys.path.insert(0, str(ROOT / 'tools'))
    import pins
    env = pins.use_haxelib()
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / 'src'
        shutil.copytree(RAY.parents[1], src)
        spans = {}
        for name, text in texts.items():
            before, rest = text.split(BEGIN, 1)
            region, after = rest.split(END, 1)
            constants = region.split(MIDDLE, 1)[0] if MIDDLE in region else region
            kept = before + BEGIN + constants + END + after
            first = before.count('\n') + 1
            spans[name] = (first, first + (BEGIN + constants).count('\n'))
            (src / 'helix/ray' / name).write_text(kept, encoding='utf-8')
        out = Path(tmp) / 'ray.xml'
        fields = Path(tmp) / 'fields.json'
        args = ['haxe', '-cp', str(src), '-lib', 'helix-services', '-lib', 'helix-platform', '-lib', 'helix-formats', '-lib', 'helix-geometry', '-lib', 'helix-math', '-lib', 'helix-log',
                '--macro', "include('helix.ray.raylib')", '--macro', "include('helix.ray', false)", '-xml', str(out), '-D', 'doc-gen', '--no-output', '-js', str(Path(tmp) / 'unused.js'),
                # The facades' macro functions are in the macro context alone, which -xml doesn't describe.
                '-cp', str(ROOT / 'tools/haxe'), '--macro', f'Fields.write("{fields.as_posix()}", {json.dumps(["helix.ray." + n[:-3] for n in texts])})']
        ran = subprocess.run(args, env=env, capture_output=True, text=True)
        if ran.returncode:
            raise SystemExit('gen_raylib: the sections don\'t compile:\n' + ran.stdout + ran.stderr)
        classes = {c.get('path'): c for c in ET.parse(out).getroot()}
        facades = {f'helix.ray.{n[:-3]}' for n in texts}
        facade_fields = [(f['owner'], f['name'], f['line'], f['isMacro']) for f in json.loads(fields.read_text(encoding='utf-8'))
                         if f['isStatic'] and f['owner'] in facades]
    sections = {}
    for name, _ in SECTIONS:
        functions = [Function(n) for n in classes[f'helix.ray.raylib.{name}']
                     if n.get('set') == 'method' and n.get('static') == '1' and FUNCTION.fullmatch(n.tag)]
        sections[name] = sorted(functions, key=lambda f: f.line)
    own = {name: {} for name in texts}
    for path, field, line, is_macro in facade_fields:
        name = path.rsplit('.', 1)[1] + '.hx'
        first, last = spans[name]
        if not first <= int(line) <= last:
            own[name][field] = is_macro
    return sections, own


def generated(file_sections, functions, api, header, written):
    """A file's generated part, between and including its markers: its header's constants not written by hand, then forwards to its
    sections' functions, then the functions a program can't call: the sections' marked `@:unsupported` or `@:unimplemented`, and the
    header's no section writes."""
    out = [BEGIN, f"\t// {header}'s constants that aren't written above, then its functions; edit a function in its section, then run",
           '\t// python3 tools/gen_raylib.py.']
    # The header's enum values: plain constants, as raylib's are, so a program's BLEND_ADDITIVE names the value even where the function
    # taking it doesn't compile yet.
    for e in api.get('enums', []):
        values = [v for v in e['values'] if v['name'] not in written]
        if values:
            out += [f"\t// ---- {sentence(e['description']).rstrip('.')} ({e['name']}), not written by hand ----", '']
            for v in values:
                out += [f"\t/** {sentence(v['description'])} */", f"\tpublic static inline final {v['name']} = {v['value']};", '']
                written.add(v['name'])
    # Its number defines too, as rlgl's RL_QUADS and RL_SRC_ALPHA; not the GL names rlgl keeps for itself.
    defines = [d for d in api.get('defines', []) if d['type'] in ('INT', 'FLOAT', 'DOUBLE') and d['name'] not in written
               and re.fullmatch(r'[A-Z][A-Z0-9_]*', d['name']) and not d['name'].startswith(('GL_', 'RLGL_'))]
    if defines:
        out += [f"\t// ---- {header}'s number defines, not written by hand ----", '']
        for d in defines:
            about = sentence(d['description']) or f"{header}'s `{d['name']}`."
            out += [f"\t/** {about} */", f"\tpublic static inline final {d['name']} = {d['value']};", '']
    out += [MIDDLE, '\t#if !macro']
    unsupported, unimplemented = [], []
    for name, title in file_sections:
        out += ['', f'\t// ---- {title} (raylib/{name}.hx) ----', '']
        for f in functions[name]:
            if f.refusal:
                # Declared here as a macro, so the build stops at the program's call, with the section's message.
                kind, message = f.refusal
                doc = ' '.join(f.doc.split('@param')[0].split('@return')[0].split())
                (unsupported if kind == 'unsupported' else unimplemented).extend(
                    refusal(f.name, [(p[0], p[1]) for p in f.params], f.result, message, doc, kind, f.full_result))
                continue
            # A rest parameter is spread into the call, as its values, not passed as one.
            call = f'{name}.{f.name}({", ".join("..." + p[0] if p[3].startswith("haxe.extern.Rest") else p[0] for p in f.params)})'
            out += [f'\t/** {f.doc} */', *wrapped(f'\tpublic static inline function {f.name}({f.signature()}):{f.result}'),
                    f'\t\t{call if f.result == "Void" else "return " + call};', '']
    out += ['\t#end', '']
    if unsupported:
        out += [f"\t// ---- {header}'s functions helix-ray won't have: each refuses to compile, saying why and what to use ----", ''] + unsupported
    missing = [f for f in api['functions'] if f['name'] not in written]
    if unimplemented or missing:
        out += [f"\t// ---- {header}'s functions helix-ray doesn't have yet: each refuses to compile, saying so ----", ''] + unimplemented
        callbacks = callback_types(api)
        for f in missing:
            out += stub(f, header, callbacks)
    out += [END]
    # As the formatter lays it out, so formatting leaves it as it is: no blank line just inside the #if or before its #end, and never two.
    lines = []
    for line in out:
        if line == '' and (not lines or lines[-1] in ('', '\t#if !macro')):
            continue
        if line == '\t#end' and lines and lines[-1] == '':
            lines.pop()
        lines.append(line)
    return '\n'.join(lines)


def layout():
    """What the API reference (tools/gen_apidoc.py) groups each file's members by, from what this generator reads: {class: (headings,
    refused)}. headings names each member's heading: its section's for a function, its enum's or its header's defines' for a constant,
    and the macros the file writes by hand under one of their own. refused holds the functions a call to which doesn't compile, by kind
    ('unsupported', 'unimplemented'), each a list of names in the header's order."""
    texts = {name: (RAY / name).read_text(encoding='utf-8') for name in TARGETS}
    functions, own = described(texts)
    every = {f.name for fs in functions.values() for f in fs}
    out = {}
    for name, (target_sections, api_file, header) in TARGETS.items():
        api = json.loads((VENDOR / api_file).read_text(encoding='utf-8'))
        headings, refused = {}, {'unsupported': [], 'unimplemented': []}
        for section, title in target_sections:
            for f in functions[section]:
                if f.refusal:
                    refused[f.refusal[0]].append(f.name)
                else:
                    headings[f.name] = title
        for e in api.get('enums', []):
            for v in e['values']:
                headings.setdefault(v['name'], f"{sentence(e['description']).rstrip('.')} ({e['name']})")
        for d in api.get('defines', []):
            if d['type'] == 'COLOR':
                headings.setdefault(d['name'], 'Colors')
            elif d['type'] in ('INT', 'FLOAT', 'DOUBLE', 'FLOAT_MATH'):
                headings.setdefault(d['name'], f"{header}'s defines")
        for field, is_macro in own[name].items():
            if is_macro:
                headings.setdefault(field, 'Macros, run as the program builds')
        written = every | set(own[name])
        refused['unimplemented'] += [f['name'] for f in api['functions'] if f['name'] not in written]
        out[f'helix.ray.{name[:-3]}'] = (headings, refused)
    return out


def struct_type(s, header, callbacks):
    """A struct of raylib's helix-ray has no type for, as a class with raylib's fields."""
    lines = [GENERATED_TYPE, 'package helix.ray;', '',
             f"/** raylib's `{s['name']}` ({header}): not in helix-ray yet; its fields are raylib's. {sentence(s.get('description', ''))} */",
             f"class {s['name']} {{"]
    for field in s['fields']:
        t = haxe_type(field['type'], callbacks, True)
        initial = {'Int': ' = 0', 'Float': ' = 0', 'Bool': ' = false', 'String': ' = ""'}.get(t, ' = []' if t.startswith('Array<') else '')
        lines += [f"\t/** {sentence(field.get('description', '')) or field['name'] + '.'} */", f"\tpublic var {field['name']}:{t}{initial};", '']
    lines += ['\t/** Creates one, its fields zero, empty or null. */', '\tpublic function new() {}', '}', '']
    return '\n'.join(lines)


def alias_type(a, header):
    """An alias of raylib's helix-ray has no type for, as a typedef."""
    about = sentence(a.get('description', '')) or f"Another name for `{a['type']}`."
    return '\n'.join([GENERATED_TYPE, 'package helix.ray;', '', f"/** raylib's `{a['name']}` ({header}): {about} */",
                      f"typedef {a['name']} = {a['type']};", ''])


def main():
    sys.path.insert(0, str(ROOT / 'tools'))
    import cli
    parser = cli.parser(__doc__)
    parser.add_argument('--check', action='store_true', help='write nothing; exit 1 when anything generated is stale')
    check = parser.parse_args().check
    texts = {name: (RAY / name).read_text(encoding='utf-8') for name in TARGETS}
    for name, text in texts.items():
        if BEGIN not in text or END not in text:
            print(f'gen_raylib: {name} has no generated part (its markers are missing)')
            return 1
    functions, own = described(texts)
    # A refusal's message naming what to use instead gives its parameters as the section writes them.
    every = {f.name: f for fs in functions.values() for f in fs}
    stale = [f'{m.group(1)}({m.group(2)})' for f in every.values() if f.refusal for m in [INSTEAD.search(f.refusal[1])]
             if m and (m.group(1) not in every or every[m.group(1)].signature() != m.group(2))]
    if stale:
        print('gen_raylib: a refusal\'s message names a signature that isn\'t written so: ' + ', '.join(stale))
        return 1
    files = {}
    for name, text in texts.items():
        target_sections, api_file, header = TARGETS[name]
        api = json.loads((VENDOR / api_file).read_text(encoding='utf-8'))
        before, rest = text.split(BEGIN, 1)
        after = rest.split(END, 1)[1]
        # Written: in a section, or by hand in the file itself (its constants and macro functions).
        written = set(every) | set(own[name])
        files[RAY / name] = before + generated(target_sections, functions, api, header, written) + after
        callbacks = callback_types(api)
        for s in api['structs']:
            if s['name'] in OPAQUE:
                continue
            files.setdefault(RAY / f"{s['name']}.hx", struct_type(s, header, callbacks))
        for a in api['aliases']:
            files.setdefault(RAY / f"{a['name']}.hx", alias_type(a, header))
    changed = 0
    for path, content in files.items():
        current = path.read_text(encoding='utf-8') if path.exists() else None
        # A type written by hand is helix-ray's own; only a generated one is replaced.
        if current is not None and path.name not in TARGETS and not current.startswith(GENERATED_TYPE):
            continue
        if current == content:
            continue
        changed += 1
        if check:
            print(f'gen_raylib: {path.relative_to(ROOT)} is stale; run python3 tools/gen_raylib.py and commit it')
        else:
            path.write_text(content, encoding='utf-8')
            print(f'gen_raylib: wrote {path.relative_to(ROOT)}')
    if check and changed:
        return 1
    if not changed:
        print('gen_raylib: everything generated is current')
    return 0


if __name__ == '__main__':
    sys.exit(main())
