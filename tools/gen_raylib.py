#!/usr/bin/env python3
"""Writes the generated parts of helix-raylib's Raylib.hx, Raymath.hx, Rlgl.hx, Raygui.hx, Raylib6.hx, Rlights.hx and the modules of
helix.raylib.extras, and the types helix-raylib doesn't have yet.

Raylib.hx has RCore, RShapes, RTextures, RText, RModels and RAudio, in raylib's module order; Raymath.hx has RMath, Rlgl.hx RRlgl, and
Raygui.hx RGui and RGuiControls, raygui's API apart as raylib's examples include it, Raylib6.hx RModels6, the calls raylib 6.0 adds
that helix-raylib has before its version moves past 5.5, and Rlights.hx RLights, the rlights.h raylib's
lighting examples include. The calls a refusal names in place of raylib's are in the file of the call they replace, each section after
the raylib module it serves, so a program's import of raylib's header brings them: in Raylib.hx the window requests (RWindowAsync), the
file calls (RFilesAsync) and the compiled shaders (RCompiledShaders) after RCore, RTexturesAsync after RTextures, RTextAsync after
RText, RModelsAsync after RModels, RAudioAsync after RAudio; in Raygui.hx RGuiAsync after RGui.
What a program opts into that raylib has no call for is in the package helix.raylib.extras, a module and a section of its own each
(extras.Lighting from RLighting, extras.VirtualGamepad from RVirtualGamepad, extras.Device from RDevice, extras.GuiSkins from
RGuiSkins, extras.Debug from RDebug, extras.Sprites from RSprites, a model's posed bounds and merge in extras.Models from RModelsPosed
and RModelsMerged). The
sections (engines/raylib/src/helix/raylib/modules/) are read as the compiler describes them (haxe -xml), never by matching their text
(docs/CONVENTIONS.md). Each file's generated part has two halves:

  - its header's constants that aren't written by hand (an extras module has no header): raylib's enum values and number defines
    (engines/raylib/vendor/raylib/raylib_api.json, raymath_api.json and rlgl_api.json, raylib's own description of its API, rlgl's and
    raymath's made by raylib's parser, and engines/raylib/vendor/raygui/raygui_api.json, made from raygui.h by raylib's parser);
  - its functions: every function of its sections as an inline forward with its doc comment, under a heading naming its module and file;
    then each function a section marks `@:waits` and writes with an answer parameter after raylib's own, as a macro with raylib's
    parameters and result whose call waits in the function calling it (helix.raylib.internal.Wait);
    then each function a program can't call, as a macro taking any arguments (so a call guessing them reports the refusal, not a
    mismatch) whose call reports its message where it is (helix.platform.macros.Build), so the build stops there and the call still has
    raylib's result type. A section's function marked
    `@:unsupported("...")` is one helix-raylib won't have (Build.unsupported), one marked `@:unimplemented("...")` one it doesn't have yet
    (Build.unimplemented), and one of the header's that no section writes is declared `@:unimplemented` with "Not implemented".

So each file reads like its header, and a call costs nothing more. A refusal's message names the call beside it with no import, as the
file holding the refused call holds it too; a message naming a function of an extras module would name that module's import
(`import helix.raylib.extras.Models.*;`), as a program reaching for raylib's call doesn't import it yet, and the module it names must be
the one holding the function. An extras module is kept to MODULE_LINES lines, so none grows into a monster, and holds
no static variable with an initializer, which every program importing it would link, so dead-code elimination keeps only the functions a
program calls. The sections are compiled with the files' generated functions left out, so a stale file doesn't stop its own making. A
struct of raylib's that helix-raylib has no type for is written as a type of its own, with raylib's fields, in a file that says it is
generated; a type written by hand in its place is left alone.

    python3 tools/gen_raylib.py [--check]

The rest of each file (its own constants and macro functions) is written by hand, outside the markers. --check writes nothing and exits 1
when anything generated is stale, as helix.py test runs it."""
