def class_path(name):
    """A target's class, by its file's name: helix.raylib.Raylib for Raylib.hx, helix.raylib.extras.Models for extras/Models.hx."""
    return 'helix.raylib.' + name[:-3].replace('/', '.')


def haxe_type(c, callbacks, many):
    """A C type of raylib's as Haxe writes it. A pointer to a struct is the struct, or an array of them when many (a parameter named
    for many, a field, a result); a pointer to numbers is an array; text is a String, bytes are Bytes, a callback a function type."""
    c = c.replace('const ', '').strip()
    if c in OPAQUE:
        return OPAQUE[c]
    if c in callbacks:
        return callbacks[c]
    array = re.fullmatch(r'(\w+)\[\d+\]', c)
    if array:
        return 'String' if array.group(1) == 'char' else f'Array<{haxe_type(array.group(1), callbacks, False)}>'
    if c == 'char *':
        return 'String'
    if c == 'char **':
        return 'Array<String>'
    if c == 'unsigned char *':
        return 'haxe.io.Bytes'
    if c == 'void *':
        return 'Dynamic'
    if c.endswith('**'):
        inner = haxe_type(c[:-2].strip(), callbacks, False)
        return f'Array<{inner}>' if many == 'parameter' else f'Array<Array<{inner}>>'
    if c.endswith('*'):
        pointed = c[:-1].strip()
        inner = haxe_type(pointed, callbacks, False)
        return f'Array<{inner}>' if many or pointed in NUMBERS else inner
    return NUMBERS.get(c, c)


def sentence(text):
    """raylib's description as a sentence."""
    text = text.strip().rstrip('.')
    return text[0].upper() + text[1:] + '.' if text else ''


def callback_types(api):
    """raylib's callbacks as Haxe's function types, null for none; raylib's va_list left out, as helix-raylib's TraceLog has none."""
    out = {}
    for c in api.get('callbacks', []):
        args = ', '.join(f"{p['name']}:{haxe_type(p['type'], {}, True)}" for p in c.get('params', []) if p['type'] != 'va_list')
        out[c['name']] = f"Null<({args}) -> {haxe_type(c['returnType'], {}, True)}>"
    return out


def wrapped(line):
    """A signature or a call as the formatter lays it out: past 160 columns (a tab is 4), broken after the last comma that fits, the
    rest three tabs in."""
    if len(line.expandtabs(4)) <= 160:
        return [line]
    # Broken only between parameters, never inside a parameter's type.
    commas, depth = [], 0
    for i, c in enumerate(line):
        depth += c in '(<[' 
        depth -= c in ')]' or c == '>' and line[i - 1] != '-'  # a function type's arrow closes nothing
        if c == ',' and depth == 1 and len(line[:i + 1].expandtabs(4)) < 160:
            commas.append(i)
    cut = commas[-1]
    return [line[:cut + 1], '\t\t\t' + line[cut + 2:]]


def qualified(haxe):
    """A Haxe type with helix-raylib's types given their package, as an expression typed in the program's own scope needs them."""
    names = {p.stem for p in RAY.glob('*.hx')}
    return re.sub(r'\b([A-Z]\w*)\b', lambda m: f'helix.raylib.{m.group(1)}' if m.group(1) in names else m.group(1), haxe)


def refusal(name, result, message, doc, kind='unimplemented', full=None):
    """A function helix-raylib declares but doesn't have, as a macro: a call reports message where it is, through Build's kind (unimplemented
    or unsupported), and has raylib's result type; full is the result with its types' packages, else qualified from result. It takes any
    arguments, so a call with too few, too many or the wrong types reports message and not the mismatch; params, raylib's, are in its
    section's doc comment, and a header's own in the header."""
    becomes = {'Void': '{}', 'Int': '(0 : Int)', 'Float': '(0.0 : Float)', 'Bool': '(false : Bool)'}.get(result, f'(null : {full or qualified(result)})')
    return [f'\t/** {doc} */', *wrapped(f'\tpublic static macro function {name}(args:Array<Expr>):ExprOf<{result}>'),
            *body(f'\t\treturn helix.platform.macros.Build.{kind}("{message}", macro{becomes if becomes.startswith("(") else " " + becomes});'), '']


def body(line):
    """A refusal's body as the formatter lays it out: past 160 columns, broken after the message, the result three tabs in."""
    if len(line.expandtabs(4)) <= 160:
        return [line]
    head, tail = line.rsplit(', macro', 1)
    return [head + ',', '\t\t\tmacro' + tail]


def waiting(section, f):
    """A function a section writes with an answer parameter (`@:waits`), as a macro with raylib's parameters and result: a call waits
    for the section's answer (helix.raylib.internal.Wait.section)."""
    message = f'{f.name}: Not supported in a function used as a value.'
    params = ', '.join(f'{p[0]}:ExprOf<{p[1]}>' for p in f.params)
    line = (f'\t\treturn helix.raylib.internal.Wait.section("{message}", macro helix.raylib.modules.{section}.{f.name}, '
            f'[{", ".join(p[0] for p in f.params)}], {"true" if f.result == "Void" else "false"});')
    return [f'\t/** {f.doc} */', *wrapped(f'\tpublic static macro function {f.name}({params}):ExprOf<{f.result}>'), *wrapped(line), '']


def stub(f, header, callbacks):
    """A function of raylib's helix-raylib doesn't have, with raylib's result type: a call to it doesn't compile."""
    name = f['name']
    doc = f"raylib's `{name}` ({header}): not in helix-raylib yet, so a call to it doesn't compile. {sentence(f.get('description', ''))}".strip()
    return refusal(name, haxe_type(f['returnType'], callbacks, True), f'{name}: Not implemented', doc)


def type_text(node, full=False):
    """A type as Haxe writes it, from haxe -xml's type element: helix-raylib's own types by their short names (a file in helix.raylib finds
    them), or full with their packages."""
    if node.tag in ('c', 'x', 't', 'e'):
        path = node.get('path')
        name = path if full or path.count('.') != 2 or not path.startswith('helix.raylib.') else path.rsplit('.', 1)[1]
        params = [type_text(c, full) for c in node]
        return name + (f'<{", ".join(params)}>' if params else '')
    if node.tag == 'd':
        return 'Dynamic'
    if node.tag == 'f':
        kids = list(node)
        names = node.get('a', '').split(':') if node.get('a') else []
        args = [type_text(k, full) for k in kids[:-1]]
        result = type_text(kids[-1], full)
        if not args:
            return f'Void->{result}'
        if len(args) == 1 and not any(names) and kids[0].tag != 'f':
            return f'{args[0]}->{result}'
        named = [f'{n.lstrip("?")}:{t}' if n else t for n, t in zip(names + [''] * len(args), args)]
        return f'({", ".join(named)}) -> {result}'
    return node.tag


class Function:
    """A section's function as the compiler describes it: its name, its parameters (name, type, written as Haxe writes each), its result,
    its doc comment, and the refusal its meta asks for, if any (Build's helper and the message)."""

    def __init__(self, node):
        self.name = node.tag
        self.line = int(node.get('line', 0))
        f = node.find('f')
        kids = list(f)
        names = f.get('a').split(':') if f.get('a') else []
        values = f.get('v', '').split(':') if f.get('v') else [''] * len(names)
        self.params = []
        for name, kid, value in zip(names, kids[:-1], values + [''] * len(names)):
            text = type_text(kid)
            written = f'{name.lstrip("?")}:{text} = {value}' if value else f'{name}:{text}'
            self.params.append((name.lstrip('?'), text, written, type_text(kid, True)))
        self.result = type_text(kids[-1])
        self.full_result = type_text(kids[-1], True)
        doc = node.find('haxe_doc')
        self.doc = doc.text if doc is not None else ''
        self.refusal = None
        self.waits = False
        meta = node.find('meta')
        for m in meta if meta is not None else []:
            if m.get('n') in REFUSALS:
                # The meta's argument as written, a string literal: the message is inside its quotes.
                self.refusal = (REFUSALS[m.get('n')], m.find('e').text[1:-1])
            if m.get('n') == WAITS:
                self.waits = True
        if self.waits:
            # Its last parameter takes the answer: raylib's call has the parameters before it, and the answer's type as its result.
            answer = list(kids[-2])
            if kids[-2].tag != 'f' or len(answer) > 2 or type_text(answer[-1]) != 'Void' or self.result != 'Void':
                raise SystemExit(f'gen_raylib: {self.name} is marked @:waits, so its last parameter is answer:T->Void or '
                                 'answer:Void->Void, and it returns nothing')
            self.params.pop()
            self.result = type_text(answer[0]) if len(answer) == 2 else 'Void'
            self.full_result = type_text(answer[0], True) if len(answer) == 2 else 'Void'

    def signature(self):
        """Its parameters as a section writes them."""
        return ', '.join(p[2] for p in self.params)


def bare(declared):
    """A macro function's parameter type as a section's would be written: ExprOf<T> as T, its arrows without spaces."""
    return re.sub(r'^ExprOf<(.*)>$', r'\1', declared or '').replace(' -> ', '->')


def described(texts):
    """The sections' functions and each file's members written by hand, as the compiler describes them (haxe -xml). The sections are
    compiled over a copy of engines/raylib/src whose files keep only their generated constants (which the sections name), so a stale file doesn't
    stop its own making. Returns ({section: [Function, in order]}, {file: names written by hand}, {macro function written by hand: its
    parameters}, [each static variable an extras module gives a value, by its full name])."""
    sys.path.insert(0, str(ROOT / 'tools'))
    import pins
    env = pins.use_haxelib()
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / 'src'
        shutil.copytree(RAY.parents[1], src)
        spans = {}
        for name, text in texts.items():
            before, rest = text.split(BEGIN, 1)
            region, after = rest.split(END, 1)
            constants = region.split(MIDDLE, 1)[0] if MIDDLE in region else region
            kept = before + BEGIN + constants + END + after
            first = before.count('\n') + 1
            spans[name] = (first, first + (BEGIN + constants).count('\n'))
            (src / 'helix/raylib' / name).write_text(kept, encoding='utf-8')
        out = Path(tmp) / 'raylib.xml'
        fields = Path(tmp) / 'fields.json'
        args = ['haxe', '-cp', str(src), '-lib', 'helix-services', '-lib', 'helix-platform', '-lib', 'helix-formats', '-lib', 'helix-geometry', '-lib', 'helix-math', '-lib', 'helix-log',
                '--macro', "include('helix.raylib.modules')", '--macro', "include('helix.raylib', false)", '--macro', f"include('{EXTRAS}')", '-xml', str(out), '-D', 'doc-gen', '-D', 'helix-company=helix', '-D', 'helix-product=gen-raylib', '--no-output', '-js', str(Path(tmp) / 'unused.js'),
                # The facades' macro functions are in the macro context alone, which -xml doesn't describe.
                '-cp', str(ROOT / 'tools/haxe'), '--macro', f'Fields.write("{fields.as_posix()}", {json.dumps([class_path(n) for n in texts])})']
        ran = subprocess.run(args, env=env, capture_output=True, text=True)
        if ran.returncode:
            raise SystemExit('gen_raylib: the sections don\'t compile:\n' + ran.stdout + ran.stderr)
        classes = {c.get('path'): c for c in ET.parse(out).getroot()}
        files = {class_path(n): n for n in texts}
        declared = [f for f in json.loads(fields.read_text(encoding='utf-8')) if f['isStatic'] and f['owner'] in files]
        facade_fields = [(f['owner'], f['name'], f['line'], f['isMacro']) for f in declared]
        # A static variable an extras module gives a value, which every program importing the module would link.
        initialized = sorted(f"{f['owner']}.{f['name']}" for f in declared if f['owner'].startswith(EXTRAS + '.') and f.get('hasValue')
                             and not f.get('isInline'))
        # A macro function written by hand (LoadModelAsync), its parameters as a section writes them: each ExprOf<T> as T, its arrows bare.
        macros = {f['name']: ', '.join(('?' if a['optional'] else '') + a['name'] + ':' + bare(a['type']) for a in f['args'])
                  for f in declared if f['isMacro'] and f.get('args') is not None}
    sections = {}
    for name, _ in SECTIONS:
        functions = [Function(n) for n in classes[f'helix.raylib.modules.{name}']
                     if n.get('set') == 'method' and n.get('static') == '1' and FUNCTION.fullmatch(n.tag)]
        sections[name] = sorted(functions, key=lambda f: f.line)
    own = {name: {} for name in texts}
    for path, field, line, is_macro in facade_fields:
        name = files[path]
        first, last = spans[name]
        if not first <= int(line) <= last:
            own[name][field] = is_macro
    return sections, own, macros, initialized


def generated(file_sections, functions, api, header, written, by_hand=()):
    """A file's generated part, between and including its markers: its header's constants not written by hand, then forwards to its
    sections' functions, then the functions that wait (the sections' marked `@:waits`), then the functions a program can't call: the
    sections' marked `@:unsupported` or `@:unimplemented`, and the header's no section writes."""
    if api is None:
        # A header without an API description (rlights.h) has its functions alone, as helix-raylib's own modules do.
        whose = f"{header}'s" if header.endswith('.h') or header.startswith('raylib ') else "helix-raylib's own"
        out = [BEGIN, f"\t// {whose} functions; edit a function in its section, then run python3 tools/gen_raylib.py."]
        api = {'functions': []}
    else:
        out = [BEGIN, f"\t// {header}'s constants that aren't written above, then its functions; edit a function in its section, then run",
               '\t// python3 tools/gen_raylib.py.']
    # The header's enum values: plain constants, as raylib's are, so a program's BLEND_ADDITIVE names the value even where the function
    # taking it doesn't compile yet.
    for e in api.get('enums', []):
        values = [v for v in e['values'] if v['name'] not in written]
        if values:
            out += [f"\t// ---- {sentence(e['description']).rstrip('.')} ({e['name']}), not written by hand ----", '']
            for v in values:
                # A value the header leaves undescribed is named with its enum's description, or its header's name.
                about = sentence(v['description']) or (f"{sentence(e['description']).rstrip('.')}: `{v['name']}`." if e['description']
                                                         else f"{header}'s `{v['name']}`.")
                out += [f"\t/** {about} */", f"\tpublic static inline final {v['name']} = {v['value']};", '']
                written.add(v['name'])
    # Its number defines too, as rlgl's RL_QUADS and RL_SRC_ALPHA; not the GL names rlgl keeps for itself.
    defines = [d for d in api.get('defines', []) if d['type'] in ('INT', 'FLOAT', 'DOUBLE') and d['name'] not in written
               and re.fullmatch(r'[A-Z][A-Z0-9_]*', d['name']) and not d['name'].startswith(('GL_', 'RLGL_'))]
    if defines:
        out += [f"\t// ---- {header}'s number defines, not written by hand ----", '']
        for d in defines:
            about = sentence(d['description']) or f"{header}'s `{d['name']}`."
            out += [f"\t/** {about} */", f"\tpublic static inline final {d['name']} = {d['value']};", '']
    out += [MIDDLE, '\t#if !macro']
    waits, unsupported, unimplemented = [], [], []
    for name, title in file_sections:
        out += ['', f'\t// ---- {title} (raylib/{name}.hx) ----', '']
        for f in functions[name]:
            # A waiting call (EndDrawing) is a macro function written by hand in the file, over its section's function.
            if f.name in by_hand:
                continue
            if f.waits:
                # Declared here as a macro, so the wait is in the program's function calling it.
                waits.extend(waiting(name, f))
                continue
            if f.refusal:
                # Declared here as a macro, so the build stops at the program's call, with the section's message.
                kind, message = f.refusal
                doc = ' '.join(f.doc.split('@param')[0].split('@return')[0].split())
                (unsupported if kind == 'unsupported' else unimplemented).extend(
                    refusal(f.name, f.result, message, doc, kind, f.full_result))
                continue
            # A rest parameter is spread into the call, as its values, not passed as one.
            call = f'{name}.{f.name}({", ".join("..." + p[0] if p[3].startswith("haxe.extern.Rest") else p[0] for p in f.params)})'
            out += [f'\t/** {f.doc} */', *wrapped(f'\tpublic static inline function {f.name}({f.signature()}):{f.result}'),
                    f'\t\t{call if f.result == "Void" else "return " + call};', '']
    out += ['\t#end', '']
    if waits:
        out += [f"\t// ---- {header}'s functions that wait for a file or an answer: each a macro, its wait in the function calling it ----", ''] + waits
    if unsupported:
        out += [f"\t// ---- {header}'s functions helix-raylib won't have: each refuses to compile, saying why and what to use ----", ''] + unsupported
    missing = [f for f in api['functions'] if f['name'] not in written]
    if unimplemented or missing:
        out += [f"\t// ---- {header}'s functions helix-raylib doesn't have yet: each refuses to compile, saying so ----", ''] + unimplemented
        callbacks = callback_types(api)
        for f in missing:
            out += stub(f, header, callbacks)
    out += [END]
    # As the formatter lays it out, so formatting leaves it as it is: no blank line just inside the #if or before its #end, and never two.
    lines = []
    for line in out:
        if line == '' and (not lines or lines[-1] in ('', '\t#if !macro')):
            continue
        if line == '\t#end' and lines and lines[-1] == '':
            lines.pop()
        lines.append(line)
    return '\n'.join(lines)


def layout():
    """What the API reference (tools/gen_apidoc.py) groups each file's members by, from what this generator reads: {class: (headings,
    refused)}. headings names each member's heading: its section's for a function, its enum's or its header's defines' for a constant,
    and the macros the file writes by hand under one of their own. refused holds the functions a call to which doesn't compile, by kind
    ('unsupported', 'unimplemented'), each a list of names in the header's order."""
    texts = {name: (RAY / name).read_text(encoding='utf-8') for name in TARGETS}
    functions, own, _, _ = described(texts)
    every = {f.name for fs in functions.values() for f in fs}
    out = {}
    for name, (target_sections, api_file, header) in TARGETS.items():
        api = json.loads((VENDOR / api_file).read_text(encoding='utf-8')) if api_file else {'functions': []}
        headings, refused = {}, {'unsupported': [], 'unimplemented': []}
        for section, title in target_sections:
            for f in functions[section]:
                if f.refusal:
                    refused[f.refusal[0]].append(f.name)
                else:
                    headings[f.name] = title
        for e in api.get('enums', []):
            for v in e['values']:
                headings.setdefault(v['name'], f"{sentence(e['description']).rstrip('.')} ({e['name']})")
        for d in api.get('defines', []):
            if d['type'] == 'COLOR':
                headings.setdefault(d['name'], 'Colors')
            elif d['type'] in ('INT', 'FLOAT', 'DOUBLE', 'FLOAT_MATH'):
                headings.setdefault(d['name'], f"{header}'s defines")
        # A macro written by hand in place of a raylib call (LoadModelAsync for LoadModel) goes under that call's section, beside it.
        replaced = {f.name: title for section, title in target_sections for f in functions[section]}
        for field, is_macro in own[name].items():
            if is_macro:
                headings.setdefault(field, replaced.get(field[:-len('Async')]) if field.endswith('Async') and field[:-len('Async')] in replaced
                                    else 'Macros, run as the program builds')
        written = every | set(own[name])
        refused['unimplemented'] += [f['name'] for f in api['functions'] if f['name'] not in written]
        out[class_path(name)] = (headings, refused)
    return out


def struct_type(s, header, callbacks):
    """A struct of raylib's helix-raylib has no type for, as a class with raylib's fields."""
    lines = [GENERATED_TYPE, 'package helix.raylib;', '',
             f"/** raylib's `{s['name']}` ({header}): not in helix-raylib yet; its fields are raylib's. {sentence(s.get('description', ''))} */",
             f"class {s['name']} {{"]
    for field in s['fields']:
        t = haxe_type(field['type'], callbacks, True)
        initial = {'Int': ' = 0', 'Float': ' = 0', 'Bool': ' = false', 'String': ' = ""'}.get(t, ' = []' if t.startswith('Array<') else '')
        lines += [f"\t/** {sentence(field.get('description', '')) or field['name'] + '.'} */", f"\tpublic var {field['name']}:{t}{initial};", '']
    lines += ['\t/** Creates one, its fields zero, empty or null. */', '\tpublic function new() {}', '}', '']
    return '\n'.join(lines)


def alias_type(a, header):
    """An alias of raylib's helix-raylib has no type for, as a typedef."""
    about = sentence(a.get('description', '')) or f"Another name for `{a['type']}`."
    return '\n'.join([GENERATED_TYPE, 'package helix.raylib;', '', f"/** raylib's `{a['name']}` ({header}): {about} */",
                      f"typedef {a['name']} = {a['type']};", ''])


def main():
    sys.path.insert(0, str(ROOT / 'tools'))
    import cli
    parser = cli.parser(__doc__)
    parser.add_argument('--check', action='store_true', help='write nothing; exit 1 when anything generated is stale')
    check = parser.parse_args().check
    texts = {name: (RAY / name).read_text(encoding='utf-8') for name in TARGETS}
    for name, text in texts.items():
        if BEGIN not in text or END not in text:
            print(f'gen_raylib: {name} has no generated part (its markers are missing)')
            return 1
    functions, own, macros, initialized = described(texts)
    if initialized:
        print('gen_raylib: an extras module holds a static variable with an initializer, which every program importing it links; make it '
              'inline, or keep it in a section: ' + ', '.join(initialized))
        return 1
    # A refusal's message naming what to use instead gives its parameters as the section writes them, or as a facade's macro function
    # takes them.
    every = {f.name: f for fs in functions.values() for f in fs}
    written = {name: f.signature() for name, f in every.items()}
    written.update(macros)
    stale = [f'{m.group(1)}({m.group(2)})' for f in every.values() if f.refusal for m in [INSTEAD.search(f.refusal[1])]
             if m and written.get(m.group(1)) != m.group(2)]
    if stale:
        print('gen_raylib: a refusal\'s message names a signature that isn\'t written so: ' + ', '.join(stale))
        return 1
    # The extras module holding each function and constant of helix.raylib.extras, by its name.
    holder = {}
    for name, (target_sections, _, _) in TARGETS.items():
        if class_path(name).startswith(EXTRAS + '.'):
            for field in [f.name for section, _ in target_sections for f in functions[section]] + list(own[name]):
                holder[field] = class_path(name)
    misnamed = []
    for f in every.values():
        if not f.refusal:
            continue
        # The extras modules holding a function the message names, and those whose import it names.
        needed = {holder[name] for name in holder if re.search(rf'\b{name}\b', f.refusal[1])}
        imported = set(re.findall(rf'import ({re.escape(EXTRAS)}\.\w+)\.\*;', f.refusal[1]))
        if needed != imported:
            misnamed.append(f'{f.name} (imports {", ".join(sorted(imported)) or "none"}; its calls are in {", ".join(sorted(needed)) or "none"})')
    if misnamed:
        print('gen_raylib: a refusal\'s message names a function of an extras module without that module\'s import ("in '
              f'{EXTRAS}.Textures (import {EXTRAS}.Textures.*;)"), or the import of a module holding none it names: ' + '; '.join(misnamed))
        return 1
    files = {}
    for name, text in texts.items():
        target_sections, api_file, header = TARGETS[name]
        api = json.loads((VENDOR / api_file).read_text(encoding='utf-8')) if api_file else None
        before, rest = text.split(BEGIN, 1)
        after = rest.split(END, 1)[1]
        # Written: in a section, or by hand in the file itself (its constants and macro functions).
        written = set(every) | set(own[name])
        files[RAY / name] = before + generated(target_sections, functions, api, header, written, own[name]) + after
        lines = files[RAY / name].count('\n')
        if class_path(name).startswith(EXTRAS + '.') and lines > MODULE_LINES:
            print(f'gen_raylib: {name} would be {lines} lines, over {MODULE_LINES}: split it into modules of their own, each a raylib '
                  'module\'s or a feature\'s, each with its own section (docs/DECISIONS.md 38)')
            return 1
        if api is None:
            continue
        callbacks = callback_types(api)
        for s in api['structs']:
            if s['name'] in OPAQUE or s['name'] in COMMENTED:
                continue
            files.setdefault(RAY / f"{s['name']}.hx", struct_type(s, header, callbacks))
        for a in api['aliases']:
            files.setdefault(RAY / f"{a['name']}.hx", alias_type(a, header))
    changed = 0
    for path, content in files.items():
        current = path.read_text(encoding='utf-8') if path.exists() else None
        # A type written by hand is helix-raylib's own; only a generated one is replaced.
        if current is not None and path.relative_to(RAY).as_posix() not in TARGETS and not current.startswith(GENERATED_TYPE):
            continue
        if current == content:
            continue
        changed += 1
        if check:
            print(f'gen_raylib: {path.relative_to(ROOT)} is stale; run python3 tools/gen_raylib.py and commit it')
        else:
            path.write_text(content, encoding='utf-8')
            print(f'gen_raylib: wrote {path.relative_to(ROOT)}')
    if check and changed:
        return 1
    if not changed:
        print('gen_raylib: everything generated is current')
    return 0


if __name__ == '__main__':
    sys.exit(main())
