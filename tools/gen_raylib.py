#!/usr/bin/env python3
"""Writes the generated parts of helix-ray's Raylib.hx and Raymath.hx, and the types helix-ray doesn't have yet.

Raylib.hx has RCore, RShapes, RTextures, RText, RModels, RAudio and HelixRay, in raylib's module order, and Raymath.hx has RMath: every
raylib function of those sections in ray/src/helix/ray/raylib/, as an inline forward with its doc comment, under a heading naming its
module and file. Then every function of raylib's (ray/vendor/raylib/raylib_api.json and raymath_api.json, raylib's own description of
its API) that isn't written, and the sections' functions marked `@:unimplemented`, each as a macro with raylib's signature whose call
reports its message where it is (helix.platform.macros.Build), so the build stops there and the call still has raylib's type. So each file reads like
its header, raylib.h or raymath.h, and a call costs nothing more. A struct of raylib's that helix-ray has no type for is written as a
type of its own, with raylib's fields, in a file that says it is generated; a type written by hand in its place is left alone.

    python3 tools/gen_raylib.py [--check]

The rest of each file (its constants and its macro functions) is written by hand, outside the markers. --check writes nothing and exits 1
when anything generated is stale, as helix.py test runs it. Standard library only."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAY = ROOT / 'ray/src/helix/ray'
VENDOR = ROOT / 'ray/vendor/raylib'
BEGIN = '\t// ---- generated by tools/gen_raylib.py: begin ----'
END = '\t// ---- generated by tools/gen_raylib.py: end ----'
# A type file's first line when the type is generated.
GENERATED_TYPE = "// Generated by tools/gen_raylib.py from raylib's API: helix-ray doesn't have it yet. When it does, write it here by hand."
# Each file, its sections (raylib's modules, in raylib.h's order, and helix-ray's own last) and the API whose missing functions it
# declares; raymath apart, as raylib has it.
TARGETS = {
    'Raylib.hx': ([
        ('RCore', 'rcore: the window and frame, input, files, cameras and shaders'),
        ('RShapes', 'rshapes: 2D shapes and collisions'),
        ('RTextures', 'rtextures: textures, render textures and colors'),
        ('RText', 'rtext: text'),
        ('RModels', 'rmodels: 3D shapes, models, meshes and rays'),
        ('RAudio', 'raudio: sound'),
        ('HelixRay', "helix-ray's own: loading in a page"),
    ], 'raylib_api.json', 'raylib.h'),
    'Raymath.hx': ([('RMath', 'raymath: vectors, matrices and quaternions')], 'raymath_api.json', 'raymath.h'),
}
SECTIONS = [s for sections, _, _ in TARGETS.values() for s in sections]
# A function of raylib's (capitalized, as raylib's names are), its doc comment and any metadata before it: group 2 is the metadata, 3
# the name, 4 the parameters, 5 the result.
FUNCTION = re.compile(r'(\t/\*\*(?:(?!\*/).)*?\*/\n)((?:\t@:[^\n]*\n)*)\tstatic function ([A-Z]\w*)\((.*?)\):\s*([^{\n]+?)\s*\{', re.S)
# A function that refuses to compile (helix.ray.internal.Unimplemented), and the one its message says to use instead, with its parameters.
UNIMPLEMENTED = re.compile(r'@:unimplemented\("[^"]*?See (\w+)\((.*?)\)"\)')
# C's number types as Haxe's.
NUMBERS = {'int': 'Int', 'unsigned int': 'Int', 'long': 'Int', 'char': 'Int', 'unsigned char': 'Int', 'unsigned short': 'Int',
           'float': 'Float', 'double': 'Float', 'bool': 'Bool', 'void': 'Void'}
# raymath's arrays of floats, and the buffers raudio keeps behind a pointer.
OPAQUE = {'float3': 'Array<Float>', 'float16': 'Array<Float>', 'rAudioBuffer *': 'Dynamic', 'rAudioProcessor *': 'Dynamic'}
# A parameter name Haxe reserves, and the name helix-ray gives it.
KEYWORDS = {'dynamic': 'isDynamic'}


def parameters(text, typed=False):
    """The names of a parameter list, in order: its `?` and types and defaults left out; or, typed, each as `name:type`."""
    names, depth, current = [], 0, ''
    # A function type's arrow isn't a closing angle bracket.
    for c in text.replace('->', '~~'):
        if c in '(<[{':
            depth += 1
        elif c in ')>]}':
            depth -= 1
        if c == ',' and depth == 0:
            names.append(current)
            current = ''
        else:
            current += c
    if current.strip():
        names.append(current)
    if typed:
        return [n.strip().split('=')[0].strip() for n in names]
    return [n.strip().lstrip('?').split(':')[0].split('=')[0].strip() for n in names]


def haxe_type(c, callbacks, many):
    """A C type of raylib's as Haxe writes it. A pointer to a struct is the struct, or an array of them when many (a parameter named
    for many, a field, a result); a pointer to numbers is an array; text is a String, bytes are Bytes, a callback a function type."""
    c = c.replace('const ', '').strip()
    if c in OPAQUE:
        return OPAQUE[c]
    if c in callbacks:
        return callbacks[c]
    array = re.fullmatch(r'(\w+)\[\d+\]', c)
    if array:
        return 'String' if array.group(1) == 'char' else f'Array<{haxe_type(array.group(1), callbacks, False)}>'
    if c == 'char *':
        return 'String'
    if c == 'char **':
        return 'Array<String>'
    if c == 'unsigned char *':
        return 'haxe.io.Bytes'
    if c == 'void *':
        return 'Dynamic'
    if c.endswith('**'):
        inner = haxe_type(c[:-2].strip(), callbacks, False)
        return f'Array<{inner}>' if many == 'parameter' else f'Array<Array<{inner}>>'
    if c.endswith('*'):
        pointed = c[:-1].strip()
        inner = haxe_type(pointed, callbacks, False)
        return f'Array<{inner}>' if many or pointed in NUMBERS else inner
    return NUMBERS.get(c, c)


def sentence(text):
    """raylib's description as a sentence."""
    text = text.strip().rstrip('.')
    return text[0].upper() + text[1:] + '.' if text else ''


def callback_types(api):
    """raylib's callbacks as Haxe's function types, null for none; raylib's va_list left out, as helix-ray's TraceLog has none."""
    out = {}
    for c in api.get('callbacks', []):
        args = ', '.join(f"{p['name']}:{haxe_type(p['type'], {}, True)}" for p in c.get('params', []) if p['type'] != 'va_list')
        out[c['name']] = f"Null<({args}) -> {haxe_type(c['returnType'], {}, True)}>"
    return out


def wrapped(line):
    """A signature as the formatter lays it out: past 160 columns (a tab is 4), broken after the last comma that fits, the rest three tabs
    in."""
    if len(line.expandtabs(4)) <= 160:
        return [line]
    # Broken only between parameters, never inside a parameter's type.
    commas, depth = [], 0
    for i, c in enumerate(line):
        depth += c in '(<[' 
        depth -= c in ')]' or c == '>' and line[i - 1] != '-'  # a function type's arrow closes nothing
        if c == ',' and depth == 1 and len(line[:i + 1].expandtabs(4)) < 160:
            commas.append(i)
    cut = commas[-1]
    return [line[:cut + 1], '\t\t\t' + line[cut + 2:]]


def qualified(haxe):
    """A Haxe type with helix-ray's types given their package, as an expression typed in the program's own scope needs them."""
    names = {p.stem for p in RAY.glob('*.hx')}
    return re.sub(r'\b([A-Z]\w*)\b', lambda m: f'helix.ray.{m.group(1)}' if m.group(1) in names else m.group(1), haxe)


def refusal(name, params, result, message, doc):
    """A function helix-ray declares but doesn't have, as a macro: a call reports message where it is and has raylib's result type."""
    rest = {n for n, t in params if re.match(r'(haxe\.extern\.)?Rest<', t)}
    signature = ', '.join(f'{n}:Array<Expr>' if n in rest else f'{n}:ExprOf<{t}>' for n, t in params)
    becomes = {'Void': '{}', 'Int': '(0 : Int)', 'Float': '(0.0 : Float)', 'Bool': '(false : Bool)'}.get(result, f'(null : {qualified(result)})')
    return [f'\t/** {doc} */', *wrapped(f'\tpublic static macro function {name}({signature}):ExprOf<{result}>'),
            *body(f'\t\treturn helix.platform.macros.Build.unimplemented("{message}", macro{becomes if becomes.startswith("(") else " " + becomes});'), '']


def body(line):
    """A refusal's body as the formatter lays it out: past 160 columns, broken after the message, the result three tabs in."""
    if len(line.expandtabs(4)) <= 160:
        return [line]
    head, tail = line.rsplit(', macro', 1)
    return [head + ',', '\t\t\tmacro' + tail]


def stub(f, header, callbacks):
    """A function of raylib's helix-ray doesn't have, with raylib's signature: a call to it doesn't compile."""
    params, given = [], f.get('params', [])
    for i, p in enumerate(given):
        if p['type'] == '...':
            params.append(('args', 'haxe.extern.Rest<Dynamic>'))
            continue
        following = given[i + 1]['name'].lower() if i + 1 < len(given) else ''
        many = 'parameter' if p['name'].endswith('s') or 'count' in following or following == 'instances' else False
        params.append((KEYWORDS.get(p['name'], p['name']), haxe_type(p['type'], callbacks, many)))
    name = f['name']
    doc = f"raylib's `{name}` ({header}): not in helix-ray yet, so a call to it doesn't compile. {sentence(f.get('description', ''))}".strip()
    return refusal(name, params, haxe_type(f['returnType'], callbacks, True), f'{name}: Not implemented', doc)


def generated(sections, api, header, written):
    """A file's generated part, between and including its markers: forwards to its sections, then the functions a program can't call:
    the sections' marked `@:unimplemented`, and raylib's not written."""
    out = [BEGIN, '\t// Each function here forwards to its section, where it is written; edit it there, then run python3 tools/gen_raylib.py.',
           '\t#if !macro']
    refused = []
    for name, title in sections:
        source = (RAY / 'raylib' / f'{name}.hx').read_text(encoding='utf-8')
        out += ['', f'\t// ---- {title} (raylib/{name}.hx) ----', '']
        for m in FUNCTION.finditer(source):
            doc, meta, function, params, result = m.group(1), m.group(2), m.group(3), ' '.join(m.group(4).split()), m.group(5).strip()
            marked = re.search(r'@:unimplemented\("((?:[^"\\]|\\.)*)"\)', meta)
            if marked:
                # Declared here as a macro, so the build stops at the program's call, with the section's message.
                typed = [(n.lstrip('?'), t) for n, t in (p.split(':', 1) for p in parameters(params, True))]
                refused += refusal(function, typed, result, marked.group(1), ' '.join(doc.strip()[3:-2].split('@param')[0].split()))
                continue
            # A rest parameter is spread into the call, as its values, not passed as one.
            rest = set(re.findall(r'(\w+):(?:haxe\.extern\.)?Rest<', params))
            call = f'{name}.{function}({", ".join("..." + n if n in rest else n for n in parameters(params))})'
            body = call if result == 'Void' else f'return {call}'
            out += [doc.rstrip('\n'), *meta.splitlines(), *wrapped(f'\tpublic static inline function {function}({params}):{result}'), f'\t\t{body};', '']
    out += ['\t#end', '']
    if refused:
        out += ["\t// ---- raylib's loads, which wait for a file: each refuses to compile, naming the load to use ----", ''] + refused
    # raylib's enum values not written by hand: plain constants, as raylib's are, so a program's BLEND_ADDITIVE names the value even where
    # the function taking it doesn't compile yet.
    for e in api.get('enums', []):
        values = [v for v in e['values'] if v['name'] not in written]
        if values:
            out += [f"\t// ---- {sentence(e['description']).rstrip('.')} ({e['name']}), not written by hand ----", '']
            for v in values:
                out += [f"\t/** {sentence(v['description'])} */", f"\tpublic static inline final {v['name']} = {v['value']};", '']
    missing = [f for f in api['functions'] if f['name'] not in written]
    if missing:
        out += [f"\t// ---- {header}'s functions helix-ray doesn't have yet: each refuses to compile, saying so ----", '']
        callbacks = callback_types(api)
        for f in missing:
            out += stub(f, header, callbacks)
    out += [END]
    # As the formatter lays it out, so formatting leaves it as it is: no blank line just inside the #if or before its #end, and never two.
    lines = []
    for line in out:
        if line == '' and (not lines or lines[-1] in ('', '\t#if !macro')):
            continue
        if line == '\t#end' and lines and lines[-1] == '':
            lines.pop()
        lines.append(line)
    return '\n'.join(lines)


def struct_type(s, header, callbacks):
    """A struct of raylib's helix-ray has no type for, as a class with raylib's fields."""
    lines = [GENERATED_TYPE, 'package helix.ray;', '',
             f"/** raylib's `{s['name']}` ({header}): not in helix-ray yet; its fields are raylib's. {sentence(s.get('description', ''))} */",
             f"class {s['name']} {{"]
    for field in s['fields']:
        t = haxe_type(field['type'], callbacks, True)
        initial = {'Int': ' = 0', 'Float': ' = 0', 'Bool': ' = false', 'String': ' = ""'}.get(t, ' = []' if t.startswith('Array<') else '')
        lines += [f"\t/** {sentence(field.get('description', '')) or field['name'] + '.'} */", f"\tpublic var {field['name']}:{t}{initial};", '']
    lines += ['\t/** Creates one, its fields zero, empty or null. */', '\tpublic function new() {}', '}', '']
    return '\n'.join(lines)


def alias_type(a, header):
    """An alias of raylib's helix-ray has no type for, as a typedef."""
    about = sentence(a.get('description', '')) or f"Another name for `{a['type']}`."
    return '\n'.join([GENERATED_TYPE, 'package helix.ray;', '', f"/** raylib's `{a['name']}` ({header}): {about} */",
                      f"typedef {a['name']} = {a['type']};", ''])


def main():
    sys.path.insert(0, str(ROOT / 'tools'))
    import cli
    parser = cli.parser(__doc__)
    parser.add_argument('--check', action='store_true', help='write nothing; exit 1 when anything generated is stale')
    check = parser.parse_args().check
    texts = {name: (RAY / name).read_text(encoding='utf-8') for name in TARGETS}
    for name, text in texts.items():
        if BEGIN not in text or END not in text:
            print(f'gen_raylib: {name} has no generated part (its markers are missing)')
            return 1
    sections = ''.join((RAY / 'raylib' / f'{n}.hx').read_text(encoding='utf-8') for n, _ in SECTIONS)
    # An unimplemented function's message gives the signature of what to use instead, as it is written.
    signatures = {m.group(3): ' '.join(m.group(4).split()) for m in FUNCTION.finditer(sections)}
    stale = [f'{m.group(1)}({m.group(2)})' for m in UNIMPLEMENTED.finditer(sections) if signatures.get(m.group(1)) != m.group(2)]
    if stale:
        print('gen_raylib: an @:unimplemented message names a signature that isn\'t written so: ' + ', '.join(stale))
        return 1
    files = {}
    for name, text in texts.items():
        target_sections, api_file, header = TARGETS[name]
        api = json.loads((VENDOR / api_file).read_text(encoding='utf-8'))
        before, rest = text.split(BEGIN, 1)
        after = rest.split(END, 1)[1]
        # Written: in a section, or by hand in the file itself (its macro functions).
        written = set(signatures) | set(re.findall(r'function (\w+)\(', before + after))
        written |= set(re.findall(r'final (\w+) =', before + after))
        files[RAY / name] = before + generated(target_sections, api, header, written) + after
        callbacks = callback_types(api)
        for s in api['structs']:
            if s['name'] in OPAQUE:
                continue
            files.setdefault(RAY / f"{s['name']}.hx", struct_type(s, header, callbacks))
        for a in api['aliases']:
            files.setdefault(RAY / f"{a['name']}.hx", alias_type(a, header))
    changed = 0
    for path, content in files.items():
        current = path.read_text(encoding='utf-8') if path.exists() else None
        # A type written by hand is helix-ray's own; only a generated one is replaced.
        if current is not None and path.name not in TARGETS and not current.startswith(GENERATED_TYPE):
            continue
        if current == content:
            continue
        changed += 1
        if check:
            print(f'gen_raylib: {path.relative_to(ROOT)} is stale; run python3 tools/gen_raylib.py and commit it')
        else:
            path.write_text(content, encoding='utf-8')
            print(f'gen_raylib: wrote {path.relative_to(ROOT)}')
    if check and changed:
        return 1
    if not changed:
        print('gen_raylib: everything generated is current')
    return 0


if __name__ == '__main__':
    sys.exit(main())
