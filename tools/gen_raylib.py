#!/usr/bin/env python3
"""Writes helix-ray's Raylib.hx generated part: every public function of the sections in ray/src/helix/ray/raylib/ (RCore, RShapes,
RTextures, RText, RModels, RAudio, RMath, HelixRay), in raylib's module order, as an inline forward with its doc comment, under a
heading naming its module and file. So Raylib.hx reads like raylib.h, the whole API in one place, and a call costs nothing more.

    python3 tools/gen_raylib.py [--check]

The rest of Raylib.hx (its constants, its macro functions and the refusals of what isn't here) is written by hand, outside the markers.
--check writes nothing and exits 1 when the generated part is stale, as helix.py test runs it. Standard library only."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAY = ROOT / 'ray/src/helix/ray'
TARGET = RAY / 'Raylib.hx'
BEGIN = '\t// ---- generated by tools/gen_raylib.py: begin ----'
END = '\t// ---- generated by tools/gen_raylib.py: end ----'
# raylib's modules, in raylib.h's order, and helix-ray's own last.
SECTIONS = [
    ('RCore', 'rcore: the window and frame, input, files, cameras and shaders'),
    ('RShapes', 'rshapes: 2D shapes and collisions'),
    ('RTextures', 'rtextures: textures, render textures and colors'),
    ('RText', 'rtext: text'),
    ('RModels', 'rmodels: 3D shapes, models, meshes and rays'),
    ('RAudio', 'raudio: sound'),
    ('RMath', 'raymath: vectors, matrices and quaternions'),
    ('HelixRay', "helix-ray's own: loading in a page"),
]
FUNCTION = re.compile(r'(\t/\*\*(?:(?!\*/).)*?\*/\n)\tpublic static function (\w+)\((.*?)\):\s*([^{\n]+?)\s*\{', re.S)


def parameters(text):
    """The names of a parameter list, in order: its `?` and types and defaults left out."""
    names, depth, current = [], 0, ''
    # A function type's arrow isn't a closing angle bracket.
    for c in text.replace('->', '~~'):
        if c in '(<[{':
            depth += 1
        elif c in ')>]}':
            depth -= 1
        if c == ',' and depth == 0:
            names.append(current)
            current = ''
        else:
            current += c
    if current.strip():
        names.append(current)
    return [n.strip().lstrip('?').split(':')[0].split('=')[0].strip() for n in names]


def generated():
    """The generated part, between and including its markers."""
    out = [BEGIN, '\t// Each function here forwards to its section, where it is written; edit it there, then run python3 tools/gen_raylib.py.',
           '\t#if !macro']
    for name, title in SECTIONS:
        source = (RAY / 'raylib' / f'{name}.hx').read_text(encoding='utf-8')
        out += ['', f'\t// ---- {title} (raylib/{name}.hx) ----', '']
        for m in FUNCTION.finditer(source):
            doc, function, params, result = m.group(1), m.group(2), ' '.join(m.group(3).split()), m.group(4).strip()
            call = f'{name}.{function}({", ".join(parameters(params))})'
            body = call if result == 'Void' else f'return {call}'
            out += [doc.rstrip('\n'), f'\tpublic static inline function {function}({params}):{result}', f'\t\t{body};', '']
    out += ['\t#end', '', END]
    # As the formatter lays it out, so formatting leaves it as it is: no blank line just inside the #if or before its #end, and never two.
    lines = []
    for line in out:
        if line == '' and (not lines or lines[-1] in ('', '\t#if !macro')):
            continue
        if line == '\t#end' and lines and lines[-1] == '':
            lines.pop()
        lines.append(line)
    return '\n'.join(lines)


def main():
    sys.path.insert(0, str(ROOT / 'tools'))
    import cli
    parser = cli.parser(__doc__)
    parser.add_argument('--check', action='store_true', help='write nothing; exit 1 when the generated part is stale')
    check = parser.parse_args().check
    text = TARGET.read_text(encoding='utf-8')
    if BEGIN not in text or END not in text:
        print('gen_raylib: Raylib.hx has no generated part (its markers are missing)')
        return 1
    before, rest = text.split(BEGIN, 1)
    after = rest.split(END, 1)[1]
    # A function written in a section has no refusal left in the hand-written part.
    clash = [m.group(2) for m in FUNCTION.finditer(''.join((RAY / 'raylib' / f'{n}.hx').read_text(encoding='utf-8') for n, _ in SECTIONS))
             if f'Missing.refuse("{m.group(2)}"' in before + after]
    if clash:
        print('gen_raylib: written in a section and still refused in Raylib.hx (remove the refusal): ' + ', '.join(clash))
        return 1
    updated = before + generated() + after
    if check:
        if updated != text:
            print('gen_raylib: ray/src/helix/ray/Raylib.hx is stale; run python3 tools/gen_raylib.py and commit it')
            return 1
        print('gen_raylib: Raylib.hx is current')
        return 0
    TARGET.write_text(updated, encoding='utf-8')
    print('gen_raylib: wrote Raylib.hx')
    return 0


if __name__ == '__main__':
    sys.exit(main())
