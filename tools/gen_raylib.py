#!/usr/bin/env python3
"""Writes the generated parts of helix-ray's Raylib.hx and Raymath.hx: every raylib function of the sections in
ray/src/helix/ray/raylib/, as an inline forward with its doc comment, under a heading naming its module and file. Raylib.hx has RCore,
RShapes, RTextures, RText, RModels, RAudio and HelixRay, in raylib's module order, and Raymath.hx has RMath. So each reads like its
header, raylib.h or raymath.h, and a call costs nothing more.

    python3 tools/gen_raylib.py [--check]

The rest of each file (its constants, its macro functions and the refusals of what isn't here) is written by hand, outside the markers.
--check writes nothing and exits 1 when a generated part is stale, as helix.py test runs it. Standard library only."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RAY = ROOT / 'ray/src/helix/ray'
BEGIN = '\t// ---- generated by tools/gen_raylib.py: begin ----'
END = '\t// ---- generated by tools/gen_raylib.py: end ----'
# Each file and its sections: raylib's modules, in raylib.h's order, and helix-ray's own last; raymath apart, as raylib has it.
TARGETS = {
    'Raylib.hx': [
        ('RCore', 'rcore: the window and frame, input, files, cameras and shaders'),
        ('RShapes', 'rshapes: 2D shapes and collisions'),
        ('RTextures', 'rtextures: textures, render textures and colors'),
        ('RText', 'rtext: text'),
        ('RModels', 'rmodels: 3D shapes, models, meshes and rays'),
        ('RAudio', 'raudio: sound'),
        ('HelixRay', "helix-ray's own: loading in a page"),
    ],
    'Raymath.hx': [('RMath', 'raymath: vectors, matrices and quaternions')],
}
SECTIONS = [s for sections in TARGETS.values() for s in sections]
# A function of raylib's (capitalized, as raylib's names are), its doc comment and any metadata before it: group 2 is the metadata, 3 the name, 4 the parameters, 5 the result.
FUNCTION = re.compile(r'(\t/\*\*(?:(?!\*/).)*?\*/\n)((?:\t@:[^\n]*\n)*)\tstatic function ([A-Z]\w*)\((.*?)\):\s*([^{\n]+?)\s*\{', re.S)
# A function that refuses to compile (helix.ray.internal.Unimplemented), and the one its message says to use instead, with its parameters.
UNIMPLEMENTED = re.compile(r'@:unimplemented\("[^"]*?See (\w+)\((.*?)\)"\)')


def parameters(text):
    """The names of a parameter list, in order: its `?` and types and defaults left out."""
    names, depth, current = [], 0, ''
    # A function type's arrow isn't a closing angle bracket.
    for c in text.replace('->', '~~'):
        if c in '(<[{':
            depth += 1
        elif c in ')>]}':
            depth -= 1
        if c == ',' and depth == 0:
            names.append(current)
            current = ''
        else:
            current += c
    if current.strip():
        names.append(current)
    return [n.strip().lstrip('?').split(':')[0].split('=')[0].strip() for n in names]


def generated(sections):
    """A file's generated part, between and including its markers, forwarding to its sections."""
    out = [BEGIN, '\t// Each function here forwards to its section, where it is written; edit it there, then run python3 tools/gen_raylib.py.',
           '\t#if !macro']
    for name, title in sections:
        source = (RAY / 'raylib' / f'{name}.hx').read_text(encoding='utf-8')
        out += ['', f'\t// ---- {title} (raylib/{name}.hx) ----', '']
        for m in FUNCTION.finditer(source):
            doc, meta, function, params, result = m.group(1), m.group(2), m.group(3), ' '.join(m.group(4).split()), m.group(5).strip()
            call = f'{name}.{function}({", ".join(parameters(params))})'
            # A function that doesn't compile is declared here as it is in its section, so the build stops at the program's call.
            body = f'throw "{function} is unimplemented"' if '@:unimplemented' in meta else call if result == 'Void' else f'return {call}'
            out += [doc.rstrip('\n'), *meta.splitlines(), f'\tpublic static inline function {function}({params}):{result}', f'\t\t{body};', '']
    out += ['\t#end', '', END]
    # As the formatter lays it out, so formatting leaves it as it is: no blank line just inside the #if or before its #end, and never two.
    lines = []
    for line in out:
        if line == '' and (not lines or lines[-1] in ('', '\t#if !macro')):
            continue
        if line == '\t#end' and lines and lines[-1] == '':
            lines.pop()
        lines.append(line)
    return '\n'.join(lines)


def main():
    sys.path.insert(0, str(ROOT / 'tools'))
    import cli
    parser = cli.parser(__doc__)
    parser.add_argument('--check', action='store_true', help='write nothing; exit 1 when a generated part is stale')
    check = parser.parse_args().check
    texts = {name: (RAY / name).read_text(encoding='utf-8') for name in TARGETS}
    for name, text in texts.items():
        if BEGIN not in text or END not in text:
            print(f'gen_raylib: {name} has no generated part (its markers are missing)')
            return 1
    # A function written in a section has no refusal left in a hand-written part.
    sections = ''.join((RAY / 'raylib' / f'{n}.hx').read_text(encoding='utf-8') for n, _ in SECTIONS)
    clash = [m.group(3) for m in FUNCTION.finditer(sections) if any(f'Missing.refuse("{m.group(3)}"' in text for text in texts.values())]
    if clash:
        print('gen_raylib: written in a section and still refused by hand (remove the refusal): ' + ', '.join(clash))
        return 1
    # An unimplemented function's message gives the signature of what to use instead, as it is written.
    signatures = {m.group(3): ' '.join(m.group(4).split()) for m in FUNCTION.finditer(sections)}
    stale = [f'{m.group(1)}({m.group(2)})' for m in UNIMPLEMENTED.finditer(sections) if signatures.get(m.group(1)) != m.group(2)]
    if stale:
        print('gen_raylib: an @:unimplemented message names a signature that isn\'t written so: ' + ', '.join(stale))
        return 1
    for name, text in texts.items():
        before, rest = text.split(BEGIN, 1)
        updated = before + generated(TARGETS[name]) + rest.split(END, 1)[1]
        if updated == text:
            print(f'gen_raylib: {name} is current')
        elif check:
            print(f'gen_raylib: ray/src/helix/ray/{name} is stale; run python3 tools/gen_raylib.py and commit it')
            return 1
        else:
            (RAY / name).write_text(updated, encoding='utf-8')
            print(f'gen_raylib: wrote {name}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
